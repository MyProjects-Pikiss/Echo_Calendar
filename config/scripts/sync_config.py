CONFIG_PATH = Path("config/echo-calendar.config.env")


def parse_key_values(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def require_value(values: dict[str, str], key: str) -> str:
    value = values.get(key, "").strip()
    if not value:
        raise SystemExit(f"Missing required config key: {key}")
    return value


def value(values: dict[str, str], key: str, default: str = "") -> str:
    return values.get(key, default).strip()


def expand_local_path(raw: str, repo_root: Path) -> str:
    expanded = raw.strip().strip("\"").strip("'")
    userprofile = os.environ.get("USERPROFILE", "").strip()
    if not userprofile:
        parts = repo_root.resolve().parts
        if len(parts) >= 5 and parts[1].lower() == "mnt" and parts[3].lower() == "users":
            userprofile = f"{parts[2].upper()}:\\Users\\{parts[4]}"
    replacements = {
        "%USERPROFILE%": userprofile,
        "%HOMEDRIVE%": os.environ.get("HOMEDRIVE", "").strip(),
        "%HOMEPATH%": os.environ.get("HOMEPATH", "").strip(),
    }
    for marker, replacement in replacements.items():
        if replacement:
            expanded = expanded.replace(marker, replacement)
    return os.path.expandvars(expanded)


def local_output_path(raw: str, repo_root: Path) -> Path:
    expanded = expand_local_path(raw, repo_root)
    if os.name != "nt" and len(expanded) >= 3 and expanded[1] == ":" and expanded[2] in {"\\", "/"}:
        drive = expanded[0].lower()
        rest = expanded[3:].replace("\\", "/")
        return Path("/mnt") / drive / rest
    return Path(expanded)


def positive_int(values: dict[str, str], key: str) -> str:
    raw = require_value(values, key)
    if not raw.isdigit() or int(raw) <= 0:
        raise SystemExit(f"{key} must be a positive integer")
    return raw


