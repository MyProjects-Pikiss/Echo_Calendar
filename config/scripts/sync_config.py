def render_docker_defaults(values: dict[str, str], min_supported: str | None = None) -> str:
    output: list[str] = [
        "# Generated by config/scripts/sync_config.py from config/echo-calendar.config.env.",
        "# Safe Docker defaults. Secrets and production overrides belong in the external env file.",
        "",
    ]
    for key in SERVER_DEFAULT_KEYS:
        if key == "APP_MIN_SUPPORTED_VERSION_CODE" and min_supported is not None:
            output.append(f"{key}={min_supported}")
        else:
            output.append(f"{key}={value(values, key)}")
        if key in {"SERVER_MODE", "LLM_MAX_OUTPUT_TOKENS", "ALLOW_SIGNUP", "KOREA_HOLIDAY_API_MAX_CONCURRENCY", "USAGE_DB_PATH", "KAFKA_CLIENT_ID", "HOLIDAY_DAILY_WINDOW_YEARS"}:
            output.append("")

    output.extend(
        [
            "APP_LATEST_VERSION_CODE=" + positive_int(values, "APP_VERSION_CODE"),
            "APP_LATEST_VERSION_NAME=" + require_value(values, "APP_VERSION_NAME"),
            "",
            "OPENAI_API_KEY=",
            "KOREA_HOLIDAY_API_KEY=",
            "USAGE_DASHBOARD_OWNER_USERNAME=",
            "USAGE_DASHBOARD_ACCESS_KEY=",
            "USAGE_ADMIN_USERNAME=",
            "USAGE_ADMIN_PASSWORD=",
        ]
    )
    return "\n".join(output).rstrip() + "\n"


