def render_runtime_version(values: dict[str, str], min_supported: str | None = None) -> str:
    min_code = min_supported or value(values, "APP_MIN_SUPPORTED_VERSION_CODE", positive_int(values, "APP_VERSION_CODE"))
    lines = [
        "APP_LATEST_VERSION_CODE=" + positive_int(values, "APP_VERSION_CODE"),
        "APP_LATEST_VERSION_NAME=" + require_value(values, "APP_VERSION_NAME"),
        "APP_MIN_SUPPORTED_VERSION_CODE=" + min_code,
    ]
    return "\n".join(lines) + "\n"


def build_outputs(repo_root: Path, values: dict[str, str], sync_min_supported: bool) -> dict[Path, str]:
    min_supported = positive_int(values, "APP_VERSION_CODE") if sync_min_supported else None
    external_downloads_dir = local_output_path(require_value(values, "BACKEND_DOWNLOADS_DIR"), repo_root)
    return {
        repo_root / "app" / "APP_CLIENT_CONFIG.txt": render_app_client_config(values),
        repo_root / "app" / "APP_SIGNING_PATH.txt": render_app_signing_path(values),
        repo_root / "server" / ".env": render_server_dotenv(values, repo_root),
        repo_root / "server" / "docker.defaults.env": render_docker_defaults(values, min_supported),
        repo_root / "server" / "SERVER_ENV_TEMPLATE.env": render_server_external_template(values, min_supported),
        external_downloads_dir / "app_version.env": render_runtime_version(values, min_supported),
    }


def write_outputs(outputs: dict[Path, str], check: bool) -> bool:
    changed = False
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            print(f"[sync-config] already-synced: {path}")
            continue
        changed = True
        if check:
            print(f"[sync-config] would-update: {path}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"[sync-config] updated: {path}")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Sync generated Echo Calendar config files from config/echo-calendar.config.env."
    )
    parser.add_argument("--check", action="store_true", help="Only check whether generated files are up to date.")
    parser.add_argument(
        "--sync-min-supported",
        action="store_true",
        help="Legacy option: generate APP_MIN_SUPPORTED_VERSION_CODE from APP_VERSION_CODE for this run.",
    )
    args = parser.parse_args(argv)

    repo_root = Path(__file__).resolve().parents[2]
    config_path = repo_root / CONFIG_PATH
    values = parse_key_values(config_path)
    if not values:
        raise SystemExit(f"Config file not found or empty: {config_path}")

    outputs = build_outputs(repo_root, values, args.sync_min_supported)
    changed = write_outputs(outputs, args.check)
    if args.check and changed:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
