        "APP_VERSION_CODE=" + version_code,
        "APP_VERSION_NAME=" + version_name,
        "",
        "AI_API_TIMEOUT_MS=" + value(values, "AI_API_TIMEOUT_MS", "30000"),
        "HOLIDAY_SYNC_TIMEOUT_MS=" + value(values, "HOLIDAY_SYNC_TIMEOUT_MS", "5000"),
        "ALLOW_SIGNUP=" + value(values, "ALLOW_SIGNUP", "false"),
        "AI_SEND_CLIENT_API_KEY_DEBUG=" + value(values, "AI_SEND_CLIENT_API_KEY_DEBUG", "false"),
        "AI_SEND_CLIENT_API_KEY_RELEASE=" + value(values, "AI_SEND_CLIENT_API_KEY_RELEASE", "false"),
        "AI_REQUIRE_HTTPS_DEBUG=" + value(values, "AI_REQUIRE_HTTPS_DEBUG", "false"),
